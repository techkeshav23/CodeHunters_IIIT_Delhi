"""Run the full pipeline on the organisers' dataset and write docs/RESULTS.md.

    python -m scripts.report_org
    python -m scripts.report_org --out docs/RESULTS.md --now 2026-10-24T11:00:00+05:30

Every row of data/sanocare_v1/triage_dataset.jsonl goes through app.pipeline.run in
interactive mode (as /v1/triage does) with the deployed model. "Now" is fixed so the
caregiver slots, and so the whole report apart from date and latency, are reproducible.
Git is only read (rev-parse, status).
"""
from __future__ import annotations

import argparse
import json
import platform
import subprocess
import sys
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app import config  # noqa: E402
from app.config import urgency_rank  # noqa: E402
from app.matching.caregivers import load  # noqa: E402
from app.triage.model import MODEL_PATH, get_model  # noqa: E402
from eval.metrics import confusion, macro_f1, ndcg_at_k, per_class, percentile  # noqa: E402
from eval.run_eval import evaluate, load_rows  # noqa: E402

DEFAULT_DATA = config.ORG_DATA_DIR / "triage_dataset.jsonl"
DEFAULT_NOW = "2026-10-24T11:00:00+05:30"
CARE_ORDER = ["paramedic", "nurse", "lab", "gp", "emergency", "followup"]
CARE_NAME = {"paramedic": "paramedic_home_visit", "nurse": "home_nursing", "lab": "lab_test_home",
             "gp": "teleconsultation", "emergency": "emergency_112", "followup": "follow-up", "none": "none"}
URG_ORDER = ["routine", "same_day", "immediate", "followup"]
URG_NAME = {"routine": "scheduled", "same_day": "same_day", "immediate": "emergency", "followup": "asked first",
            "none": "none"}
LANGS = ["English", "Hinglish", "Hindi"]


def git(*args: str) -> str | None:
    try:
        out = subprocess.run(["git", "--no-optional-locks", *args], cwd=ROOT, capture_output=True, text=True,
                             timeout=10)
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout.strip() if out.returncode == 0 else None


def f3(x: float | None) -> str:
    return "n/a" if x is None or x != x else f"{x:.3f}"


def frac(a: int, b: int) -> str:
    return f"{a} / {b} ({a / b:.3f})" if b else f"{a} / 0"


def cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return out


def ordered(keys, order: list[str]) -> list[str]:
    keys = set(keys)
    return [k for k in order if k in keys] + sorted(keys - set(order))


def confusion_table(gold: list[str], pred: list[str], order: list[str], names: dict) -> list[str]:
    conf = confusion(gold, pred)
    rows_k = ordered(gold, order)
    cols_k = ordered(set(gold) | set(pred), order)
    rows = [[names.get(g, g)] + [conf[g].get(p, 0) or "." for p in cols_k] + [sum(conf[g].values())]
            for g in rows_k]
    return table(["label / ours"] + [names.get(c, c) for c in cols_k] + ["rows"], rows)


def care_scores(rs: list[dict]) -> tuple[float, float]:
    gold, pred = [r["gold_care"] for r in rs], [r["pred_care"] for r in rs]
    return sum(g == p for g, p in zip(gold, pred)) / len(rs), macro_f1(gold, pred)


def build(results: list[dict], raw: list[dict], meta: dict | None, info: dict) -> str:
    gold_by_id = {r["id"]: r for r in raw}
    L: list[str] = []
    w = L.append

    w("# Raahat results on the organisers' dataset")
    w("")
    w(f"- Date: {info['date']}")
    w(f"- Git commit: {info['commit']}{' (working tree has uncommitted changes)' if info['dirty'] else ''}")
    w(f"- Data: `{info['data']}` ({len(results)} rows), caregivers: {info['roster']}")
    w(f"- Pipeline: `app.pipeline.run`, interactive mode (as `/v1/triage`), follow-up policy "
      f"`{config.FOLLOWUP_POLICY}`, top-k {config.TOP_K}, clock fixed at {info['now']}")
    if meta:
        s = meta.get("settings", {})
        w(f"- Model: `{info['model_path']}`, trained {meta.get('trained_at')}, rules weight "
          f"{s.get('rules_weight')}, emergency threshold {s.get('emergency_threshold')}")
    else:
        w("- Model: not loaded, rules only")
    w(f"- Generated by `python -m scripts.report_org` on {info['platform']}")
    w("")
    w("The deployed model is trained on all 66 distinct messages in this file, so sections 1 to 5 are "
      "in-sample: they show whether the running service reproduces the labels, not how it does on new "
      "messages. The held-out estimate is in section 6.")
    w("")

    # 1. care type ------------------------------------------------------------
    w("## 1. Care type")
    w("")
    w("All rows; a row labelled with `care_type: null` and a follow-up question counts as the class "
      "`follow-up`, and is right only if we ask.")
    w("")
    acc, mf1 = care_scores(results)
    rows = [["all", len(results), f3(acc), f3(mf1)]]
    for lg in LANGS:
        rs = [r for r in results if r["category"] == lg]
        if rs:
            a, m = care_scores(rs)
            rows.append([lg, len(rs), f3(a), f3(m)])
    L += table(["detected_language", "rows", "accuracy", "macro-F1"], rows)
    w("")
    pc = per_class([r["gold_care"] for r in results], [r["pred_care"] for r in results])
    L += table(["class", "precision", "recall", "F1", "rows"],
               [[CARE_NAME.get(k, k), f3(v["precision"]), f3(v["recall"]), f3(v["f1"]), v["support"]]
                for k, v in ((k, pc[k]) for k in ordered(pc, CARE_ORDER))])
    w("")
    w("Confusion (rows: label, columns: our answer; `.` = 0):")
    w("")
    L += confusion_table([r["gold_care"] for r in results], [r["pred_care"] for r in results], CARE_ORDER,
                         CARE_NAME)
    w("")
    wrong = [r for r in results if r["gold_care"] != r["pred_care"]]
    if wrong:
        w("Rows where the care type differs (distinct messages):")
        w("")
        by_msg = Counter((r["text"], r["gold_care"], r["pred_care"]) for r in wrong)
        L += table(["message", "label", "ours", "rows"],
                   [[t, CARE_NAME.get(g, g), CARE_NAME.get(p, p), n] for (t, g, p), n in by_msg.most_common()])
        w("")

    # 2. urgency --------------------------------------------------------------
    urg = [r for r in results if r["gold_urgency"]]
    w("## 2. Urgency")
    w("")
    w(f"Rows with a labelled urgency ({len(urg)}; the follow-up rows have none). Asking a question on "
      "such a row counts as a wrong urgency.")
    w("")
    gold_u, pred_u = [r["gold_urgency"] for r in urg], [r["pred_urgency"] for r in urg]
    lower = sum(1 for g, p in zip(gold_u, pred_u) if urgency_rank(p) < urgency_rank(g))
    L += table(["rows", "accuracy", "macro-F1", "lower than the label"],
               [[len(urg), f3(sum(g == p for g, p in zip(gold_u, pred_u)) / len(urg)), f3(macro_f1(gold_u, pred_u)),
                 lower]])
    w("")
    L += confusion_table(gold_u, pred_u, URG_ORDER, URG_NAME)
    w("")

    # 3. follow-up ------------------------------------------------------------
    fu = [r for r in results if r["gold_care"] == "followup"]
    decided = [r for r in results if r["gold_care"] != "followup"]
    asked_fu = [r for r in fu if r["follow_up"]]
    false_asks = [r for r in decided if r["follow_up"]]
    w("## 3. Follow-up questions")
    w("")
    w(f"- Rows labelled \"ask first\" where we ask: {frac(len(asked_fu), len(fu))}")
    w(f"- Rows with a labelled care type where we ask instead (false asks): {frac(len(false_asks), len(decided))}")
    qids = Counter(r["follow_up_id"] for r in results if r["follow_up"])
    if qids:
        w(f"- Questions asked: {', '.join(f'`{q}` x {n}' for q, n in qids.most_common())}")
    if false_asks:
        w(f"- False asks: {', '.join(sorted(set(r['text'] for r in false_asks)))}")
    w("")

    # 4. safety ---------------------------------------------------------------
    em = [r for r in results if r["gold_care"] == "emergency"]
    non = [r for r in results if r["gold_care"] != "emergency"]
    missed = [r for r in em if not r["pred_emergency"]]
    false_em = [r for r in non if r["pred_emergency"]]
    w("## 4. Safety")
    w("")
    w(f"- Emergency recall: {frac(len(em) - len(missed), len(em))}")
    w(f"- False emergencies (non-emergency rows sent to 112): {frac(len(false_em), len(non))}")
    if missed:
        w(f"- Missed: {', '.join(r['id'] + ' ' + repr(r['text']) for r in missed)}")
    if false_em:
        w(f"- False emergencies: {', '.join(r['id'] + ' ' + repr(r['text']) for r in false_em)}")
    w("")
    gold_flag_sets = Counter(tuple(gold_by_id[r["id"]]["response"].get("red_flags") or []) for r in em)
    if len(gold_flag_sets) == 1:
        only = list(next(iter(gold_flag_sets)))
        w(f"Every emergency row in the dataset is labelled `red_flags = {json.dumps(only)}`, whatever the "
          "message says (a collapse, bleeding after an accident). A set match against these labels would "
          "mostly measure that labelling, so the table lists the flags we return per message instead.")
    else:
        w("Labelled red-flag lists on emergency rows: "
          + "; ".join(f"{list(k)} x {n}" for k, n in gold_flag_sets.most_common()) + ".")
    w("")
    per_msg: dict[str, dict] = {}
    for r in em:
        d = per_msg.setdefault(r["text"], {"lang": r["category"], "n": 0, "flags": Counter()})
        d["n"] += 1
        d["flags"][tuple(r["api_red_flags"])] += 1
    L += table(["message", "language", "rows", "our red_flags"],
               [[t, d["lang"], d["n"], "; ".join(", ".join(k) or "(none)" for k in d["flags"])]
                for t, d in sorted(per_msg.items(), key=lambda kv: (LANGS.index(kv[1]["lang"])
                                                                    if kv[1]["lang"] in LANGS else 9, kv[0]))])
    w("")

    # 5. matching -------------------------------------------------------------
    w("## 5. Caregiver matching")
    w("")
    w("End to end: our care type, our ranking, against `matched_caregivers` in the label. The label keeps the "
      "first 1 to 3 of the reference ranking, so k is the label's length: list match means our first k ids "
      "equal the label in order; precision@k is the share of our first k found in the label; NDCG@3 grades "
      "the label by position (`eval.metrics.ndcg_at_k`).")
    w("")
    has_gold = [r for r in results if r["gold_care"] != "emergency" and r["gold_matches"]]

    def match_row(name: str, rs: list[dict]) -> list:
        if not rs:
            return [name, 0, "n/a", "n/a", "n/a"]
        lm = sum(r["matched"][:len(r["gold_matches"])] == r["gold_matches"] for r in rs)
        pk = sum(len(set(r["matched"][:len(r["gold_matches"])]) & set(r["gold_matches"])) / len(r["gold_matches"])
                 for r in rs) / len(rs)
        nd = sum(ndcg_at_k(r["matched"], r["gold_matches"], 3) for r in rs) / len(rs)
        return [name, len(rs), frac(lm, len(rs)), f3(pk), f3(nd)]

    mrows = [match_row("all rows with labelled caregivers", has_gold),
             match_row("of which our care type is right", [r for r in has_gold if r["pred_care"] == r["gold_care"]])]
    for c in CARE_ORDER:
        rs = [r for r in has_gold if r["gold_care"] == c]
        if rs:
            mrows.append(match_row(f"label {CARE_NAME[c]}", rs))
    L += table(["rows", "n", "list match", "precision@k", "NDCG@3"], mrows)
    w("")
    k_dist = Counter(len(r["gold_matches"]) for r in has_gold)
    w(f"Label length k: {', '.join(f'{k} caregiver(s) in {n} rows' for k, n in sorted(k_dist.items()))}.")
    w("")
    extra = [r for r in results if r["matched"] and not r["gold_matches"]]
    missing = [r for r in results if r["gold_matches"] and not r["matched"]]
    w(f"- We return caregivers, the label has none: {len(extra)} rows"
      + (f" ({', '.join(f'{CARE_NAME.get(c, c)} {n}' for c, n in Counter(r['gold_care'] for r in extra).most_common())})"
         if extra else ""))
    w(f"- The label has caregivers, we return none: {len(missing)} rows"
      + (f" ({', '.join(f'{CARE_NAME.get(c, c)} {n}' for c, n in Counter(r['gold_care'] for r in missing).most_common())})"
         if missing else ""))
    empty_both = [r for r in results if r["gold_care"] not in ("emergency", "followup")
                  and not r["gold_matches"] and not r["matched"]]
    if empty_both:
        w(f"- Both empty on a decided non-emergency row: {len(empty_both)} rows "
          f"({', '.join(f'{CARE_NAME.get(c, c)} {n}' for c, n in Counter(r['gold_care'] for r in empty_both).most_common())})")
    for title, rs in (("We return caregivers, label empty", extra), ("Label has caregivers, we return none", missing)):
        if rs:
            w("")
            w(f"{title}, by message:")
            w("")
            by_msg = Counter((r["text"], CARE_NAME.get(r["gold_care"], r["gold_care"]),
                              CARE_NAME.get(r["pred_care"], r["pred_care"])) for r in rs)
            L += table(["message", "label care type", "our care type", "rows"],
                       [[t, g, p, n] for (t, g, p), n in by_msg.most_common()])
    w("")

    # 6. held-out model numbers ----------------------------------------------
    w("## 6. The model on held-out situations")
    w("")
    if not meta:
        w("No model metadata (`models/triage_meta.json`) found.")
    else:
        w(f"The {meta.get('rows')} rows hold only {meta.get('distinct_messages')} distinct messages: "
          f"{meta.get('situations')} situations, each written in English, Hinglish and Hindi (other rows repeat "
          "a message with a different location). A random row split would put the same message, or its "
          "translation, on both sides and score the model on text it was trained on, so `scripts/train_triage.py` "
          "splits by situation, all three languages together.")
        w("")
        split = meta.get("split", {})
        w(f"- Test: {len(split.get('test_situations', []))} situations, one per class, seed {split.get('seed')}: "
          f"{', '.join(f'`{s}`' for s in split.get('test_situations', []))}. Not used for any choice.")
        w(f"- Validation: {split.get('validation')}; it picked C = {meta.get('C')} and rules weight "
          f"{meta.get('settings', {}).get('rules_weight')}.")
        w(f"- The deployed model was then refit on all {meta.get('situations')} situations with those settings.")
        w("")
        w("\"Model + rules\" is what the API does: red-flag rules first, then a model emergency above its "
          "threshold, then the blend of model and rules. \"Model alone\" is the model's top class with no rules.")
        w("")
        sc = meta.get("scores", {})
        n_train = (meta.get("situations") or 0) - len(split.get("test_situations", []))
        names = [("train_fit", f"training fit ({n_train} situations)"),
                 ("validation", "validation, model + rules"),
                 ("validation_model_alone", "validation, model alone"),
                 ("test", "test, model + rules"),
                 ("test_model_alone", "test, model alone")]
        L += table(["", "messages", "accuracy", "macro-F1", "emergency recall", "false emergency"],
                   [[label, sc[k].get("n"), f3(sc[k].get("accuracy")), f3(sc[k].get("macro_f1")),
                     f3(sc[k].get("emergency_recall")), f3(sc[k].get("false_emergency"))]
                    for k, label in names if k in sc])
        w("")
        by_lang = sc.get("test_by_language") or {}
        if by_lang:
            w("Test (model + rules) by language:")
            w("")
            L += table(["language", "messages", "accuracy", "macro-F1"],
                       [[lg, v.get("n"), f3(v.get("accuracy")), f3(v.get("macro_f1"))] for lg, v in by_lang.items()])
            w("")
        w(f"With 18 test messages, one wrong answer moves accuracy by {1 / 18:.3f}.")
        if meta.get("latency"):
            w(f"Model latency at training time (features + predict): p50 {meta['latency'].get('p50_ms')} ms, "
              f"p95 {meta['latency'].get('p95_ms')} ms.")
        w("")

    # 7. latency --------------------------------------------------------------
    t_in = [r["timing_ms"] for r in results if r["timing_ms"] is not None]
    t_wall = [r["wall_ms"] for r in results]
    w("## 7. Latency")
    w("")
    w(f"Per request, in process (no HTTP), {len(results)} requests, one after another:")
    w("")
    L += table(["measure", "p50 ms", "p95 ms", "max ms"],
               [["pipeline (`trace.timing_ms`)", f"{percentile(t_in, 0.5):.1f}", f"{percentile(t_in, 0.95):.1f}",
                 f"{max(t_in):.1f}"],
                ["call to `run()` incl. response object", f"{percentile(t_wall, 0.5):.1f}",
                 f"{percentile(t_wall, 0.95):.1f}", f"{max(t_wall):.1f}"]])
    w("")
    return "\n".join(L).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", type=Path, default=DEFAULT_DATA)
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "RESULTS.md")
    ap.add_argument("--now", default=DEFAULT_NOW, help="fixed clock for caregiver slots (ISO time)")
    args = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")

    config.NOW_OVERRIDE = args.now
    raw = [json.loads(line) for line in args.data.read_text(encoding="utf-8-sig").splitlines() if line.strip()]
    rows = load_rows(args.data)
    model = get_model()
    pool, source = load()
    evaluate(rows[:5], mode="interactive")  # warm caches so latency is per request, not start-up
    results = evaluate(rows, mode="interactive")["results"]
    assert [r["id"] for r in results] == [r["id"] for r in raw], "row order changed"

    try:
        data_rel = args.data.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        data_rel = str(args.data)
    try:
        model_rel = MODEL_PATH.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        model_rel = str(MODEL_PATH)
    info = {
        "date": datetime.now().strftime("%Y-%m-%d %H:%M"),
        "commit": git("rev-parse", "--short", "HEAD") or "unknown",
        "dirty": bool(git("status", "--porcelain", "--untracked-files=no")),
        "data": data_rel, "roster": f"{len(pool)} from `{source}`", "now": args.now,
        "model_path": model_rel,
        "platform": f"Python {platform.python_version()}, {platform.system()} {platform.release()}",
    }
    text = build(results, raw, model.meta if model else None, info)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({len(results)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
