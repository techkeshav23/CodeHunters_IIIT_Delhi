/// UI text for [key] in [lang]; `{name}` placeholders are filled from [vars].
String t(Lang lang, K key, [Map<String, Object> vars = const {}]) {
  final e = _strings[key]!;
  var s = switch (lang) {
    Lang.hinglish => e.$1,
    Lang.hi => e.$2,
    Lang.en => e.$3,
  };
  vars.forEach((k, v) => s = s.replaceAll('{$k}', v.toString()));
  return s;
}

